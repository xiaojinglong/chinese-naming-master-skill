WUXING = ["金", "木", "水", "火", "土"]
# 相生: 木→火→土→金→水→木
SHENG = {"木": "火", "火": "土", "土": "金", "金": "水", "水": "木"}
# 相克: 木→土→水→火→金→木
KE = {"木": "土", "土": "水", "水": "火", "火": "金", "金": "木"}

def relation(a, b):
    """a 对 b 的关系（a 生 b / b 生 a / a 克 b / b 克 a / 比和）"""
    if a == b:
        return "比和"
    if SHENG[a] == b:
        return "相生"   # a 生 b
    if SHENG[b] == a:
        return "相生"   # b 生 a
    if KE[a] == b:
        return "相克"   # a 克 b
    return "相克"       # b 克 a

def sancai_score(tian, ren, di):
    """天→人、人→地 两步生克打分"""
    s = 0
    r1, r2 = relation(tian, ren), relation(ren, di)
    for r in (r1, r2):
        if r == "相生":
            s += 1
        elif r == "相克":
            s -= 1
        # 比和 0
    return s, r1, r2

def sancai_grade(score):
    if score >= 2: return "大吉"
    if score == 1: return "吉"
    if score == 0: return "半吉"
    if score == -1: return "半凶"
    return "凶"


META_COMPOUND = {
    "name": "复姓库",
    "version": "1.0",
    "count_placeholder": None,
    "fields": ["surname","traditional","pinyin","strokes_kangxi_each","wuxing_each","notes"],
    "note": "strokes_kangxi_each 为两字各自的康熙笔画（供五格计算：天格=两字笔画相加+1 等）",
}

def to_records(rows, fields, common=False):
    out = []
    for r in rows:
        rec = dict(zip(fields[4:] if fields[4] == "notes" else fields[4:], r[4:])) if False else {}
        rec = {
            "surname": r[0], "traditional": r[1], "pinyin": r[2],
        }
        if isinstance(r[3], list):
            rec["strokes_kangxi_each"] = r[3]
            rec["strokes_kangxi_total"] = sum(r[3])
            rec["wuxing_each"] = r[4]
        else:
            rec["strokes_kangxi"] = r[3]
            rec["wuxing"] = r[4]
        if len(r) > 5:
            rec["notes"] = r[5]
        if common:
            rec["common"] = True
        out.append(rec)
    return out

